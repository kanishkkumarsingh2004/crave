async function main() {
  console.log('Seeding Zepto-style CraveXP Dark Store catalog...')
  for (const p of ZEPTO_PRODUCTS) {
    await prisma.craveXPProduct.upsert({
      where: { id: p.id },
      update: {
        name: p.name,
        category: p.category,
        unit: p.unit,
        price: p.price,
        mrp: p.mrp,
        description: p.description,
        image: p.image,
        in_stock: p.in_stock,
        stock_count: p.stock_count,
        is_veg: p.is_veg,
      },
      create: {
        id: p.id,
        name: p.name,
        category: p.category,
        unit: p.unit,
        price: p.price,
        mrp: p.mrp,
        description: p.description,
        image: p.image,
        in_stock: p.in_stock,
        stock_count: p.stock_count,
        is_veg: p.is_veg,
        hsn_sac_code: '996331',
        price_tax_mode: 'TAX_INCLUSIVE',
      },
    })
  }
  const count = await prisma.craveXPProduct.count()
  console.log(`Successfully seeded ${count} CraveXP Zepto-style products into the dark store catalog!`)
  process.exit(0)
}

main().catch((err) => {
  console.error('Seed error:', err)
  process.exit(1)
})
